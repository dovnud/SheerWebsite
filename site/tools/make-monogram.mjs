// Extracts the S and D outlines from Bodoni Moda into src/gl/monogram-paths.ts (run once; the output is committed).
// usage: node tools/make-monogram.mjs [weight=700]
import opentype from 'opentype.js';
import fs from 'fs';
const weight = process.argv[2] || '700';
const buf = fs.readFileSync(`node_modules/@fontsource/bodoni-moda/files/bodoni-moda-latin-${weight}-normal.woff`);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const chars = ['S', 'D'];
const glyphs = chars.map((c) => font.charToGlyph(c));
const bb = glyphs.map((g) => g.getBoundingBox());
const capH = Math.max(...bb.map((b) => b.y2 - b.y1));
const k = 2.4 / capH;                       // normalise cap height to 2.4 units
const gap = 0.06 * capH;
let x = 0; const out = {};
glyphs.forEach((g, i) => {
  const dx = x - bb[i].x1;                  // left edge at x
  out[chars[i]] = g.path.commands.map((c) => { const r = { type: c.type }; for (const key of ['x', 'y', 'x1', 'y1', 'x2', 'y2']) if (key in c) r[key] = +((key.startsWith('x') ? (c[key] + dx) : c[key] - bb[i].y1) * k).toFixed(3); return r; });
  x += (bb[i].x2 - bb[i].x1) + gap;
});
const total = (x - gap) * k;
fs.writeFileSync('src/gl/monogram-paths.ts', `// Generated by tools/make-monogram.mjs from Bodoni Moda ${weight}. Do not edit.\nexport const MONOGRAM_WIDTH = ${total.toFixed(3)};\nexport const MONOGRAM_HEIGHT = 2.4;\nexport type Cmd = { type: string; x?: number; y?: number; x1?: number; y1?: number; x2?: number; y2?: number };\nexport const MONOGRAM: Record<'S' | 'D', Cmd[]> = ${JSON.stringify(out)};\n`);
console.log('width', total.toFixed(2), 'commands', out.S.length, out.D.length);
